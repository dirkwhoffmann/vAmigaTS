;
; rulevern2 -- rulevern with the AGA colour delay taken out of the data.
;
; rulevern shows a step of exactly one screen column at every band boundary
; on an A1200, because a Copper ruler is made of colour register writes and
; AGA delays those by one hires pixel while the bitplanes are not delayed.
; This variant pre-rotates the bitplane pattern by that one column, so the
; edges come out straight and any REMAINING step is something else.
;
; The compensation is a rotation of the stripe pattern, not a scroll
; register. BPLCON1 moves the data in whole lores pixels, which are two
; screen columns, and the delay is one. Only a bit rotation inside the
; bitplane word can move the data by an odd number of columns:
;
;   hires        one bit  = one hires pixel  = one column
;   super hires  two bits = two shres pixels = one column
;   lores        one bit  = one lores pixel  = TWO columns
;
; So the lores section cannot be straightened. Everything that moves lores
; data or moves the ruler -- BPLCON1, DDFSTRT, the ruler's own HP -- moves
; it by an even number of columns, and an even number can never close an
; odd gap. The lores section is left uncompensated on purpose: it keeps the
; one column step, and standing next to two straightened sections it is the
; clearest statement this suite can make that the delay is an odd number of
; columns, which is to say exactly one hires pixel.
;
; Read the picture as: hires and super hires straight, lores stepped by one
; column, and the lower half of every section stepped by four lores pixels
; because the ruler starts half a stripe late there.
;
; On an ECS machine there is no delay to cancel, so this variant is the one
; that comes out WRONG there -- hires and super hires step by one column the
; other way while lores is straight. rulevern is the test to photograph on
; ECS; this one is for AGA.
;
	include "../../../../include/registers.i"
	include "../../../../include/ministartup.i"

LVL3_INT_VECTOR     equ $6C
BPLCON3             equ $106           ; ECS and AGA
BRDRBLNK            equ $0020          ; BPLCON3 bit 5

BPLCON0_OFF         equ $0201          ; ECSENA set, no bitplanes
LORES_BITS          equ $0201
HIRES_BITS          equ $8201
SHRES_BITS          equ $0241

DIW_START           equ $2C71          ; left of the data, so the data is the edge
DIW_STOP            equ $2CC1

RULER_A             equ $FFF           ; white, and the bitplane stripes
RULER_B             equ $00A           ; blue, and COLOR00 on the data lines
RULER_0             equ $F00           ; first stripe, so the train has a start
RULER_9             equ $0F0           ; and a finish

BUF_SIZE            equ 1024

MAIN:
	lea     CUSTOM,a1
	move.w  #$7FFF,INTENA(a1)
	move.w  #$7FFF,DMACON(a1)
	move.w  #BPLCON0_OFF,BPLCON0(a1)
	move.b  #$7F,$BFDD00
	move.b  #$7F,$BFED01
	lea     irq3(pc),a3
	move.l  a3,LVL3_INT_VECTOR

	; One buffer per section, each drawing the same stripe on the screen:
	; eight lores pixels on and eight off, which is one ruler stripe.
	lea     bitL(pc),a2
	bsr     .fillLores
	lea     bitH(pc),a2
	bsr     .fillHires
	lea     bitS(pc),a2
	bsr     .fillShres

	lea     ptrL(pc),a4
	lea     bitL(pc),a3
	bsr     .patchPtrs
	lea     ptrH(pc),a4
	lea     bitH(pc),a3
	bsr     .patchPtrs
	lea     ptrS(pc),a4
	lea     bitS(pc),a3
	bsr     .patchPtrs

	lea     CUSTOM,a1
	lea     copper(pc),a0
	move.l  a0,COP1LC(a1)
	move.w  COPJMP1(a1),d0

	move.w  #$8080,DMACON(a1)   ; Copper DMA
	move.w  #$8100,DMACON(a1)   ; Bitplane DMA
	move.w  #$8200,DMACON(a1)   ; DMAEN
	move.w  #$C020,INTENA(a1)
.mainLoop:
	bra.b   .mainLoop

.fillLores:
	move.w  #(BUF_SIZE/4)-1,d0
.flLoop:
	move.w  #$FF00,(a2)+
	move.w  #$FF00,(a2)+
	dbra    d0,.flLoop
	rts

.fillHires:
	; The same stripe as rulevern, rotated one bit left. One hires pixel
	; is one screen column, so this pulls the data a column left and
	; cancels the delay on the ruler.
	move.w  #(BUF_SIZE/4)-1,d0
.fhLoop:
	move.w  #$FFFE,(a2)+
	move.w  #$0001,(a2)+
	dbra    d0,.fhLoop
	rts

.fillShres:
	; Rotated two bits left: a super hires pixel is half a column, so two
	; of them make the one column the ruler is delayed by.
	move.w  #(BUF_SIZE/8)-1,d0
.fsLoop:
	move.w  #$FFFF,(a2)+
	move.w  #$FFFC,(a2)+
	clr.w   (a2)+
	move.w  #$0003,(a2)+
	dbra    d0,.fsLoop
	rts

.patchPtrs:
	move.l  a3,d3
.ppLoop:
	move.l  (a4)+,d4
	beq.s   .ppDone
	move.l  d4,a2
	move.l  d3,d5
	swap    d5
	move.w  d5,2(a2)
	move.w  d3,6(a2)
	bra.s   .ppLoop
.ppDone:
	rts

irq3:
	movem.l d0-a6,-(sp)
	move.w  #$3FFF,INTREQ(a1)
	movem.l (sp)+,d0-a6
	rte

