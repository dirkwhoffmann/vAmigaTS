PROBE_COL           equ $0F00              ; what the Copper tries to write
LOCK_COL            equ $0FFF              ; what MAIN tries to write

NPLANES             equ 5
LINEBYTES           equ 40


MAIN:
	lea     CUSTOM,a1
	move.w  #$7FFF,INTENA(a1)
	move.w  #$7FFF,DMACON(a1)
	move.w  #BPLCON0_OFF,BPLCON0(a1)
	move.w  #$0000,BPLCON3(a1)      ; colour bank 0, LOCT clear
	move.b  #$7F,$BFDD00
	move.b  #$7F,$BFED01
	lea     irq3(pc),a3
	move.l  a3,LVL3_INT_VECTOR

	bsr     .buildPlanes
	bsr     .seed
	bsr     .readBack
	bsr     .derive
	bsr     .patchCopper

	lea     CUSTOM,a1
	lea     copper(pc),a0
	move.l  a0,COP1LC(a1)
	move.w  COPJMP1(a1),d0

	move.w  #$8080,DMACON(a1)       ; Copper DMA
	move.w  #$8100,DMACON(a1)       ; Bitplane DMA
	move.w  #$8200,DMACON(a1)       ; DMAEN
	move.w  #$C020,INTENA(a1)
.mainLoop:
	bra.b   .mainLoop

; Five bitplanes holding a horizontal ramp of colour indices: eight lores
; pixels, which is exactly one byte, per index. Forty bytes per line, so
; the forty bands show 0 to 31 and then 0 to 7 again. The modulos are -40,
; so every line refetches these same forty bytes and the bands come out as
; clean vertical columns.
.buildPlanes:
	lea     planes(pc),a3
	moveq   #0,d2                   ; plane
.bpPlane:
	moveq   #0,d3                   ; byte, and therefore band
.bpByte:
	move.w  d3,d4
	and.w   #31,d4
	moveq   #0,d5
	btst    d2,d4
	beq.s   .bpZero
	moveq   #-1,d5
.bpZero:
	move.b  d5,(a3)+
	addq.w  #1,d3
	cmp.w   #LINEBYTES,d3
	bne.s   .bpByte
	addq.w  #1,d2
	cmp.w   #NPLANES,d2
	bne.s   .bpPlane
	rts

; The seed, written with RDRAM clear so it lands on every chipset. A green
; ramp in the low nibble pair, with blue added over the upper sixteen so
; that a readback can be told from its own mirror image.
.seed:
	move.w  #BPLCON2_BASE,BPLCON2(a1)
	lea     COLOR00(a1),a2
	moveq   #0,d0
.sdLoop:
	move.w  d0,d1
	and.w   #15,d1
	lsl.w   #4,d1
	cmp.w   #16,d0
	blo.s   .sdNoBlue
	or.w    #$000F,d1
.sdNoBlue:
	move.w  d1,(a2)+
	addq.w  #1,d0
	cmp.w   #32,d0
	bne.s   .sdLoop
	rts

; RDRAM set: the registers are supposed to read back, and to stop
; accepting writes. Both are put to the test here, the write on COLOR31.
.readBack:
	move.w  #BPLCON2_RD,BPLCON2(a1)
	lea     COLOR00(a1),a2
	lea     readback(pc),a3
	moveq   #31,d0
.rbLoop:
	move.w  (a2)+,(a3)+
	dbra    d0,.rbLoop
	move.w  #LOCK_COL,COLOR31(a1)   ; dropped on AGA, taken elsewhere
	move.w  #BPLCON2_BASE,BPLCON2(a1)
	rts

; displayed[n] = (n & 15) << 8 | readback[n] & $FF. COLOR31 is left alone;
; it is carrying the write lock probe.
.derive:
	lea     COLOR00(a1),a2
	lea     readback(pc),a3
	lea     derived(pc),a4
	moveq   #0,d0
.deLoop:
	move.w  (a3)+,d1
	and.w   #$00FF,d1
	move.w  d0,d2
	and.w   #15,d2
	lsl.w   #8,d2
	or.w    d2,d1
	move.w  d1,(a4)+
	cmp.w   #31,d0
	beq.s   .deSkip
	move.w  d1,(a2)
.deSkip:
	addq.l  #2,a2
	addq.w  #1,d0
	cmp.w   #32,d0
	bne.s   .deLoop
	rts

; The Copper list carries three things it cannot know at assembly time:
; the bitplane pointers, the background colour at the top of the frame,
; and the eight values that undo the write probe.
.patchCopper:
	lea     copPtr(pc),a3
	lea     planes(pc),a4
	move.l  a4,d3
	moveq   #NPLANES-1,d0
.pcPtr:
	move.l  d3,d4
	swap    d4
	move.w  d4,2(a3)
	move.w  d3,6(a3)
	addq.l  #8,a3
	add.l   #LINEBYTES,d3
	dbra    d0,.pcPtr

	lea     copCol0(pc),a3
	move.w  derived(pc),2(a3)

	lea     copRest(pc),a3
	lea     derived+2(pc),a4
	moveq   #7,d0
.pcRest:
	move.w  (a4)+,2(a3)
	addq.l  #4,a3
	dbra    d0,.pcRest
	rts

irq3:
	movem.l d0-a6,-(sp)
	move.w  #$3FFF,INTREQ(a1)
	movem.l (sp)+,d0-a6
	rte


