
; rdram -- BPLCON2 bit 8, on AGA and on everything else.
;
; RDRAM turns the colour registers into a readable, and at the same time
; write protected, palette RAM. It exists on AGA only; on OCS and ECS the
; bit is not decoded, so a machine without AGA does the opposite of an
; A1200 in both halves of this picture.
;
;   upper half   Thirty-two vertical bands, one per colour register. The
;                colours are not immediates. MAIN seeds the registers with
;                a green ramp, sets RDRAM, READS all thirty-two back, and
;                builds the displayed palette out of what came back:
;
;                    displayed[n] = (n & 15) << 8  |  readback[n] & $FF
;
;                The red nibble is the band index and is always there, so
;                the ramp has a skeleton whatever the readback does. Green
;                and blue come from the register file. On a machine that
;                implements RDRAM they reproduce the seed, and the ramp is
;                yellow, turning white over the upper sixteen bands where
;                the seed carries blue. On a machine that does not, they
;                are whatever the bus happened to be holding.
;
;                Band 31 is a second, independent probe: MAIN writes $0FFF
;                to COLOR31 while RDRAM is still set and then never touches
;                it again. On AGA that write is dropped and band 31 keeps
;                its seed, a plain green. Elsewhere it is white.
;
;   lines $60-$77
;                The same question asked from the Copper instead of the
;                CPU. RDRAM is set, COLOR01 to COLOR08 are written red, and
;                RDRAM is cleared and the eight registers restored twenty
;                four lines later. On AGA nothing happens and the ramp runs
;                unbroken from top to bottom; elsewhere a red rectangle
;                sits across bands 1 to 8.
;
;   lower half   The timing. Forty back-to-back moves make a ruler, one
;                stripe per four colour clocks. Slot k is a magenta marker,
;                slot k+1 sets RDRAM, slots k+2 to k+9 are ordinary ruler
;                colours, and slot k+10 clears RDRAM again. The two BPLCON2
;                moves replace ruler moves instead of being inserted
;                between them, so every line is forty moves long and the
;                grid is rigid whatever k is.
;
;                On AGA the eight middle moves are dropped and the magenta
;                runs from slot k to slot k+10 inclusive, eleven slots or
;                176 screen columns. Elsewhere every move lands and the
;                magenta is two slots wide: slot k+1 writes BPLCON2 rather
;                than a colour, so the marker simply carries over into it.
;                The stripe at k+9 is doubled for the same reason, k+10
;                being the other BPLCON2 move. Eleven slots against two is
;                the reading, and it is not subtle.
;
;                k advances every two lines, so the frozen run walks across
;                the picture and its edges are measured against the ruler
;                it is made of. That is the timing statement: the first
;                move DROPPED is the one immediately after the BPLCON2
;                write, and the first move to LAND again is the one
;                immediately after the write that clears the bit.
;
;                Six lines at each end of the region carry a plain ruler
;                with no RDRAM write at all, as the yardstick.
;
; The picture runs to line $129, so the Copper list is re-synchronised once
; at line 256; the vertical field of a WAIT is only eight bits wide.
;
