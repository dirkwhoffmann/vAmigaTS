	dbra    d0,.fill

	; Walk the Copper list and fill in every bitplane pointer reload.
	; A word with bit 0 set starts a WAIT or SKIP, anything else is a
	; MOVE whose first word is the register offset.
	lea     copper(pc),a2
	lea     bitplanes(pc),a3
	move.l  a3,d1
.scan:
	cmp.l   #$FFFFFFFE,(a2)
	beq.s   .scandone
	move.w  (a2),d0
	btst    #0,d0
	bne.s   .next
	cmp.w   #BPL1PTH,d0
	bne.s   .trylow
	move.l  d1,d2
	swap    d2
	move.w  d2,2(a2)
	bra.s   .next
.trylow:
	cmp.w   #BPL1PTL,d0
	bne.s   .next
	move.w  d1,2(a2)
.next:
	addq.l  #4,a2
	bra.s   .scan
.scandone:

	lea     copper(pc),a0
	move.l  a0,COP1LC(a1)
	move.w  COPJMP1(a1),d0

	move.w  #$8080,DMACON(a1)   ; Copper DMA
	move.w  #$8100,DMACON(a1)   ; Bitplane DMA
	move.w  #$8200,DMACON(a1)   ; DMAEN
	move.w  #$C020,INTENA(a1)
.mainLoop:
	bra.b   .mainLoop

