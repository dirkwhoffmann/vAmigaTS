;
; colorlag -- do colour register writes lag the rest of Denise on AGA?
;
; Amiberry delays every write to a colour register by one hires pixel on
; AGA and applies it immediately on OCS and ECS (drawing.cpp, the AGA color
; changes are 1 hires pixel delayed branch of expand_drga_early). vAmiga
; has no such delay on any chipset. Nothing in this suite measured it.
;
; The delay is easy to see and hard to attribute, because a Copper ruler is
; made of nothing but COLOR00 writes. Comparing a ruler against bitplane
; data across two machines tells you the two moved relative to each other
; and not which one moved. This test puts a third landmark on the same
; rasterline to break the tie.
;
;
; THE THREE LANDMARKS
; -------------------
;
; Every line in every band carries all three, as vertical edges:
;
;   the ruler         40 back to back COLOR00 moves, one per 4 CCK. These
;                     are colour register writes, so this is the family
;                     that the AGA delay is supposed to move.
;
;   the window edges  DIWSTRT and DIWSTOP, black against the ruler because
;                     BRDRBLNK forces the border to pure black whatever
;                     COLOR00 happens to be doing. Positioned by the DIW
;                     comparator, so no colour write is involved.
;
;   the data bars     one bitplane whose buffer is three empty words then
;                     one solid word, repeating, so the window is ruled by
;                     narrow bars in COLOR01. Positioned by the bitplane
;                     pipeline, so again no colour write is involved.
;
; Reading a photograph, or two photographs of different machines:
;
;   ruler moves, edges and bars stay      the colour write is delayed
;   edges and bars move, ruler stays      the bitplane and DIW paths are
;                                         delayed and colour writes are not
;   everything moves together             the whole of Denise is shifted,
;                                         which is a display centring
;                                         difference and not a chipset one
;
; The third reading is the reason for measuring against two independent
; landmarks rather than one. A photograph of a different monitor cannot
; distinguish an absolute shift from a real one, but it cannot fake a
; change in the SPACING between two edge families on the same line.
;
;
; NOTES ON THE SOURCE
; -------------------
;
; DIWSTRT is lores $8A, deliberately RIGHT of the first bitplane pixel at
; $7F. The window opens at the first BPL1DAT write rather than at DIWSTRT,
; so a DIWSTRT to the left of the data would not be a landmark at all (see
; Denise/Sprites/clip/diwclip). DIWSTOP is $1A0, inside the ruler's span,
; so both window edges can be read against the scale.
;
; The bitplane pointer is reloaded at the start of every line, so all three
; bands show the same bars on every line and the edges come out as clean
; vertical columns rather than a diagonal drift. MAIN fills in the two
; address words by walking the Copper list, which is why there is no table
; of labels here: every BPL1PTH/BPL1PTL pair in the list is patched.
;
; The ruler runs on lines that have a bitplane enabled, which the rulers
; elsewhere in this suite avoid. With one bitplane in lores the fetch takes
; one cycle in eight and the Copper keeps enough slots to place a move
; every four CCK, so the stripe train stays regular. Every fifth stripe is
; yellow, so a position can be named when comparing two photographs.
;

